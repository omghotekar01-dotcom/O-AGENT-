import { createCipheriv, createDecipheriv, createHash, randomBytes, randomUUID, timingSafeEqual } from "node:crypto";
import { DomainError } from "./core.mjs";
import { AgentRuntime } from "./agent-runtime.mjs";
import { CursorCloudClient } from "./cursor-cloud.mjs";
import { MAX_ATTACHMENT_BYTES, validateFile, attachmentForModel } from "./attachments.mjs";

const PROVIDERS = Object.freeze({
  openai: { label: "OpenAI API", defaultModel: "gpt-6-luna", env: "OPENAI_API_KEY" },
  anthropic: { label: "Claude API", defaultModel: "claude-sonnet-5", env: "ANTHROPIC_API_KEY" },
  gemini: { label: "Google Gemini API", defaultModel: "gemini-3.8-flash", env: "GEMINI_API_KEY" },
});
const hash = value => createHash("sha256").update(value).digest("hex");
const validLabel = (value, max) =>
  typeof value === "string" && value.trim().length > 0 && value.length <= max;
const nowSeconds = () => Date.now();

export class AccountHub {
  constructor(core, { env = process.env, fetchImpl = fetch, now = nowSeconds } = {}) {
    this.core = core;
    this.env = env;
    this.fetchImpl = fetchImpl;
    this.now = now;
    this.busy = new Set();
    this.cursor = new CursorCloudClient({ fetchImpl });
    this.cursorPending = new Set();
    core.data.accounts ??= { members: {}, invitations: {}, connections: {}, threads: {} };
    this.data = core.data.accounts;
    this.data.members ??= {};
    this.data.invitations ??= {};
    this.data.connections ??= {};
    this.data.threads ??= {};
    this.data.attachments ??= {};
    this.data.integrations ??= {};
    this.data.cursorSubmissions ??= {};
    this.master = null;
    if (env.OAGENT_VAULT_KEY_BASE64) {
      const decoded = Buffer.from(env.OAGENT_VAULT_KEY_BASE64, "base64");
      if (decoded.length !== 32) throw new Error("OAGENT_VAULT_KEY_BASE64 must contain exactly 32 random bytes");
      this.master = decoded;
    }
  }
  get vaultReady() { return !!this.master; }
  commit(event, meta = {}) { this.core.commit(event, meta); }

  authenticate(token) {
    if (typeof token !== "string" || token.length < 40 || token.length > 200) return null;
    // User bearer tokens are generated by crypto.randomBytes(32), never passwords.
    const target = hash(token);
    for (const member of Object.values(this.data.members)) {
      if (member.revokedAt || !member.tokenHash) continue;
      const found = Buffer.from(member.tokenHash, "hex");
      const requested = Buffer.from(target, "hex");
      if (!member.revokedAt && found.length === requested.length && timingSafeEqual(found, requested)) {
        return { id: member.id, displayName: member.displayName, role: "member" };
      }
    }
    return null;
  }

  createInvitation({ label = "New user" } = {}) {
    if (!validLabel(label, 80)) throw new DomainError(400, "Invitation label must contain 1–80 characters");
    if (Object.values(this.data.members).filter(m => !m.revokedAt).length >= 50) throw new DomainError(409, "Member limit reached");
    for (const [id, item] of Object.entries(this.data.invitations)) {
      if (item.expiresAt <= this.now()) delete this.data.invitations[id];
    }
    if (Object.keys(this.data.invitations).length >= 12) throw new DomainError(429, "Too many pending invitations");
    const code = "join_" + randomBytes(24).toString("base64url");
    const id = randomUUID();
    const expiresAt = this.now() + 15 * 60 * 1000;
    this.data.invitations[id] = { id, digest: hash(code), label: label.trim(), expiresAt };
    this.commit("account.invitation.created", { invitationId: id });
    return { invitationCode: code, label: label.trim(), expiresAt };
  }

  claimInvitation({ invitationCode, displayName }) {
    if (!validLabel(displayName, 80)) throw new DomainError(400, "Display name must contain 1–80 characters");
    if (typeof invitationCode !== "string" || !/^join_[A-Za-z0-9_-]{28,80}$/.test(invitationCode)) {
      throw new DomainError(400, "Invalid invitation code");
    }
    const wanted = hash(invitationCode);
    const pair = Object.entries(this.data.invitations).find(([, invitation]) => {
      const a = Buffer.from(invitation.digest, "hex");
      const b = Buffer.from(wanted, "hex");
      return a.length === b.length && timingSafeEqual(a, b);
    });
    if (!pair || pair[1].expiresAt <= this.now()) throw new DomainError(401, "Invitation expired or already used");
    const id = randomUUID();
    const token = "oau_" + randomBytes(32).toString("base64url");
    this.data.members[id] = { id, displayName: displayName.trim(), tokenHash: hash(token), createdAt: this.now() };
    delete this.data.invitations[pair[0]];
    this.commit("account.member.created", { memberId: id });
    return { token, user: { id, displayName: displayName.trim(), role: "member" } };
  }

  members() {
    return Object.values(this.data.members).map(({ id, displayName, createdAt, revokedAt }) =>
      ({ id, displayName, createdAt, revoked: !!revokedAt }));
  }
  revokeMember(memberId) {
    const member = this.data.members[memberId];
    if (!member || member.revokedAt) throw new DomainError(404, "Member not found");
    member.revokedAt = this.now();
    delete member.tokenHash;
    delete this.data.connections[memberId];
    delete this.data.threads[memberId];
    delete this.data.attachments?.[memberId];
    delete this.data.integrations?.[memberId];
    delete this.data.cursorSubmissions?.[memberId];
    this.commit("account.member.revoked", { memberId });
    return { revoked: true };
  }

  encrypt(userId, provider, secret) {
    if (!this.master) throw new DomainError(503, "Backend credential vault is not initialized");
    const iv = randomBytes(12);
    const cipher = createCipheriv("aes-256-gcm", this.master, iv);
    cipher.setAAD(Buffer.from("oagent-v1:" + userId + ":" + provider));
    const bytes = Buffer.concat([cipher.update(secret, "utf8"), cipher.final()]);
    return { version: 1, iv: iv.toString("base64"), tag: cipher.getAuthTag().toString("base64"),
      ciphertext: bytes.toString("base64") };
  }
  decrypt(userId, provider, record) {
    if (!this.master) throw new DomainError(503, "Backend credential vault is unavailable");
    try {
      const decipher = createDecipheriv("aes-256-gcm", this.master, Buffer.from(record.iv, "base64"));
      decipher.setAAD(Buffer.from("oagent-v1:" + userId + ":" + provider));
      decipher.setAuthTag(Buffer.from(record.tag, "base64"));
      return Buffer.concat([decipher.update(Buffer.from(record.ciphertext, "base64")), decipher.final()]).toString("utf8");
    } catch {
      throw new DomainError(503, "This account key could not be decrypted. Restore the original Windows vault settings.");
    }
  }

  listConnections(userId) {
    const mine = this.data.connections[userId] ?? {};
    return { vaultReady: this.vaultReady, providers: Object.entries(PROVIDERS).map(([id, p]) => {
      const saved = mine[id];
      return { id, label: p.label, defaultModel: p.defaultModel, connected: !!saved,
        model: saved?.model ?? p.defaultModel,
        status: saved?.status ?? "not_configured",
        lastVerifiedAt: saved?.lastVerifiedAt ?? null,
        lastError: saved?.lastError ?? null };
    }) };
  }

  saveConnection(userId, provider, { apiKey, model }) {
    const option = PROVIDERS[provider];
    if (!option) throw new DomainError(404, "Unsupported AI provider");
    if (!this.vaultReady) throw new DomainError(503, "Secure vault unavailable on this backend");
    const current = this.data.connections[userId]?.[provider];
    if (apiKey != null && (typeof apiKey !== "string" || apiKey.length < 12 || apiKey.length > 1024 || /\s/.test(apiKey))) {
      throw new DomainError(400, "Invalid provider API key");
    }
    if (!current && !apiKey) throw new DomainError(400, "API key required for a new connection");
    const targetModel = model || current?.model || option.defaultModel;
    if (typeof targetModel !== "string" || !/^[A-Za-z0-9._:/-]{2,120}$/.test(targetModel)) {
      throw new DomainError(400, "Invalid provider model ID");
    }
    this.data.connections[userId] ??= {};
    this.data.connections[userId][provider] = {
      ...(apiKey ? { secret: this.encrypt(userId, provider, apiKey) } : { secret: current.secret }),
      model: targetModel,
      status: "configured_unverified",
      lastError: null,
      lastVerifiedAt: null,
      updatedAt: this.now(),
    };
    this.commit("account.provider.configured", { userId, provider });
    return this.listConnections(userId);
  }

  deleteConnection(userId, provider) {
    if (!PROVIDERS[provider]) throw new DomainError(404, "Unsupported provider");
    if (this.data.connections[userId]) delete this.data.connections[userId][provider];
    this.commit("account.provider.disconnected", { userId, provider });
    return this.listConnections(userId);
  }

  runtime(userId, provider) {
    const connection = this.data.connections[userId]?.[provider];
    if (!PROVIDERS[provider] || !connection) throw new DomainError(503, "Connect your own provider API key in Accounts first");
    const key = this.decrypt(userId, provider, connection.secret);
    const agentThreads = this.data.threads[userId] ??= {};
    const scopedCore = {
      data: { agentThreads },
      commit: (event, meta = {}) => this.commit(event, { userId, ...meta }),
      snapshot: () => ({ workers: [], tasks: [] }),
      getTask: () => { throw new DomainError(403, "Machine tools are unavailable in personal AI chats"); },
    };
    return { runtime: new AgentRuntime(scopedCore, {
      env: { OAGENT_AI_PROVIDER: provider, OAGENT_AI_MODEL: connection.model, [PROVIDERS[provider].env]: key },
      fetchImpl: this.fetchImpl, allowTools: false,
    }), connection };
  }

  recordHealth(userId, provider, health, message) {
    const connection = this.data.connections[userId]?.[provider];
    if (!connection) return;
    connection.status = health;
    connection.lastError = message ?? null;
    if (health === "connected") connection.lastVerifiedAt = this.now();
    this.commit("account.provider.status", { userId, provider, status: health });
  }

  async verifyConnection(userId, provider) {
    const { runtime } = this.runtime(userId, provider);
    try {
      await runtime.generate([{ role: "user", content: "Say OK." }], { id: "navigator", name: "Navigator",
        role: "Personal assistant", summary: "Safe model connection check" });
      this.recordHealth(userId, provider, "connected");
      return this.listConnections(userId);
    } catch (error) {
      this.recordHealth(userId, provider, runtime.providerHealth === "rate_limited" ? "rate_limited" :
        error.status === 503 ? "rate_limited" : "failed", error.status ? error.message : "Provider verification failed");
      throw error;
    }
  }

  async send(userId, { provider, message, threadId, attachmentIds = [], githubRepository }) {
    if (!PROVIDERS[provider]) throw new DomainError(400, "Choose a supported provider");
    if (!validLabel(message, 4000)) throw new DomainError(400, "Message must contain 1–4000 characters");
    const attachments = this.resolveAttachments(userId, attachmentIds);
    const busyId = userId + ":" + (threadId ?? "new");
    if ([...this.busy].filter(key => key.startsWith(userId + ":")).length >= 2) {
      throw new DomainError(429, "Too many simultaneous personal AI requests");
    }
    if (this.busy.has(busyId)) throw new DomainError(409, "This conversation is already processing");
    this.busy.add(busyId);
    try {
      if (githubRepository != null) {
        if (attachments.length >= 3) throw new DomainError(400, "Up to three sources per AI request");
        const readme = await this.githubReadme(userId, githubRepository);
        attachments.push({ name: githubRepository + "/README.md", mimeType: "text/plain", text: readme });
      }
      const { runtime } = this.runtime(userId, provider);
      if (threadId && runtime.getThread(threadId)?.provider !== provider) {
        throw new DomainError(409, "Conversation belongs to another provider");
      }
      // Personal BYOK chats have no machine-operation agent or tool privileges.
      const result = await runtime.send({ agentId: "navigator", threadId, message, attachments });
      if (attachments.length) result.messages[result.messages.length - 2].attachments = attachments.map(a => ({ name: a.name, mimeType: a.mimeType }));
      result.provider ??= provider;
      this.commit("account.chat.saved", { userId, provider, threadId: result.id });
      this.recordHealth(userId, provider, "connected");
      return result;
    } catch (error) {
      if (error.status >= 500) this.recordHealth(userId, provider,
        error.status === 503 ? "rate_limited" : "failed", error.message);
      throw error;
    } finally { this.busy.delete(busyId); }
  }

  // Cursor Cloud is a *separate user-owned agent connection*, not an
  // OpenAI/Claude/Gemini inference key. It is never shared between members,
  // and it never grants access to the owner's local desktop worker.
  cursorStatus(userId) {
    const saved = this.data.integrations[userId]?.cursorCloud;
    return {
      connected: !!saved,
      status: saved?.status ?? "not_configured",
      identity: saved?.identity ?? null,
      keyName: saved?.keyName ?? null,
      verifiedAt: saved?.verifiedAt ?? null,
      capability: saved?.status === "connected" ? "cloud_agent_api_v1" : "unverified",
      // Never display a provider connection as a local desktop session.
      supportsDesktopCapture: false, supportsHumanApprovals: false,
    };
  }
  connectCursor(userId, { apiKey } = {}) {
    if (!this.master) throw new DomainError(503, "Encrypted credential vault required");
    if (typeof apiKey !== "string" || apiKey.length < 12 ||
        apiKey.length > 1024 || /\s/.test(apiKey)) {
      throw new DomainError(400, "Invalid Cursor API key");
    }
    this.data.integrations[userId] ??= {};
    this.data.integrations[userId].cursorCloud = {
      secret: this.encrypt(userId, "cursorCloud", apiKey),
      status: "configured_unverified", identity: null,
      keyName: null, verifiedAt: null,
    };
    delete this.data.cursorSubmissions?.[userId];
    this.commit("account.cursor.configured", { userId });
    return this.cursorStatus(userId);
  }
  disconnectCursor(userId) {
    delete this.data.integrations[userId]?.cursorCloud;
    delete this.data.cursorSubmissions?.[userId];
    this.commit("account.cursor.disconnected", { userId });
    return this.cursorStatus(userId);
  }
  cursorKey(userId) {
    const saved = this.data.integrations[userId]?.cursorCloud;
    if (!saved) throw new DomainError(409, "Connect your own Cursor Cloud API key first");
    return this.decrypt(userId, "cursorCloud", saved.secret);
  }
  async verifyCursor(userId) {
    const key = this.cursorKey(userId);
    const identity = await this.cursor.verify(key);
    const saved = this.data.integrations[userId]?.cursorCloud;
    if (!saved) throw new DomainError(409, "Cursor account disconnected");
    saved.status = "connected";
    saved.keyName = identity.keyName;
    saved.identity = identity.identity;
    saved.verifiedAt = this.now();
    this.commit("account.cursor.verified", { userId });
    return this.cursorStatus(userId);
  }
  async cursorAgents(userId) {
    return this.cursor.listAgents(this.cursorKey(userId));
  }
  async cursorAgent(userId, agentId) {
    return this.cursor.getAgent(this.cursorKey(userId), agentId);
  }
  async cursorRuns(userId, agentId) {
    return this.cursor.listRuns(this.cursorKey(userId), agentId);
  }
  async cursorRun(userId, agentId, runId) {
    return this.cursor.getRun(this.cursorKey(userId), agentId, runId);
  }
  async cursorFollowUp(userId, agentId, body = {}) {
    const key = this.cursorKey(userId);
    const requestId = body.requestId;
    if (typeof requestId !== "string" || !/^[A-Za-z0-9_-]{16,120}$/.test(requestId))
      throw new DomainError(400, "A unique request ID is required");
    // Use a bounded per-user persistent idempotency record: double taps and
    // network retries must not silently create duplicate billable runs.
    const normalized = {
      agentId, prompt: body.prompt, delivery: body.delivery ?? null,
    };
    const digest = hash(JSON.stringify(normalized));
    const saved = this.data.cursorSubmissions[userId] ??= {};
    const old = saved[requestId];
    if (old) {
      if (old.digest !== digest) throw new DomainError(409, "Request ID reused for a different operation");
      if (old.uncertain) throw new DomainError(409,
        "Cursor request outcome is uncertain. Refresh the run list before another prompt.");
      return old.response;
    }
    const inFlight = userId + ":cursor:" + agentId;
    if (this.cursorPending.has(inFlight)) throw new DomainError(409, "Another Cursor action is in progress");
    this.cursorPending.add(inFlight);
    try {
      const response = await this.cursor.followUp(key, agentId, normalized);
      saved[requestId] = { digest, response, at: this.now() };
      for (const [id] of Object.entries(saved).sort((a,b) => a[1].at - b[1].at)
        .slice(0, Math.max(0, Object.keys(saved).length - 80))) delete saved[id];
      this.commit("account.cursor.run.requested", {
        userId, agentId, runId: response.run?.id ?? response.runId ?? null,
      });
      return response;
    } catch (error) {
      // A transport error may mean Cursor accepted the prompt before the
      // response disappeared. Fail closed and don't automatically retry it.
      if (error.status === 503 || error.status === 502) {
        saved[requestId] = { digest, uncertain: true, at: this.now() };
        this.commit("account.cursor.run.uncertain", { userId, agentId });
      }
      throw error;
    } finally { this.cursorPending.delete(inFlight); }
  }
  async cursorCancel(userId, agentId, runId) {
    const key = this.cursorKey(userId);
    const response = await this.cursor.cancelRun(key, agentId, runId);
    this.commit("account.cursor.run.cancelled", { userId, agentId, runId });
    return response;
  }

  githubStatus(userId) {
    const saved = this.data.integrations[userId]?.github;
    return { connected: !!saved, login: saved?.login ?? null,
      checkedAt: saved?.checkedAt ?? null, capability: "read_only_repo_metadata_and_readme" };
  }
  async githubFetch(token, path) {
    let response;
    try {
      response = await this.fetchImpl("https://api.github.com" + path, {
        method: "GET", signal: AbortSignal.timeout(15000),
        headers: { "accept": "application/vnd.github+json",
          "x-github-api-version": "2022-11-28", "user-agent": "oagent-private-github",
          "authorization": "Bearer " + token },
      });
    } catch {
      throw new DomainError(502, "GitHub is unreachable. Retry the connection.");
    }
    if (response.status === 401) throw new DomainError(401, "GitHub rejected this personal access token");
    if (response.status === 403 || response.status === 429) {
      throw new DomainError(429, "GitHub denied access, or an API rate limit was reached");
    }
    if (response.status === 404) throw new DomainError(404, "Repository or README unavailable for this GitHub account");
    if (!response.ok) throw new DomainError(502, "GitHub request failed (HTTP " + response.status + ")");
    try { return await response.json(); }
    catch { throw new DomainError(502, "Unexpected GitHub response"); }
  }
  async connectGithub(userId, { token } = {}) {
    if (typeof token !== "string" || token.length < 20 || token.length > 512 || /\s/.test(token)) {
      throw new DomainError(400, "Enter a valid fine-grained GitHub personal access token");
    }
    if (!this.vaultReady) throw new DomainError(503, "Secure vault unavailable");
    // Never report a successful connection merely because a token was saved.
    const profile = await this.githubFetch(token, "/user");
    if (typeof profile.login !== "string" || !profile.login) {
      throw new DomainError(502, "GitHub did not verify an account identity");
    }
    this.data.integrations[userId] ??= {};
    this.data.integrations[userId].github = {
      login: profile.login, checkedAt: this.now(),
      secret: this.encrypt(userId, "integration:github", token) };
    this.commit("account.github.connected", { userId });
    return this.githubStatus(userId);
  }
  disconnectGithub(userId) {
    if (this.data.integrations[userId]) delete this.data.integrations[userId].github;
    this.commit("account.github.disconnected", { userId });
    return this.githubStatus(userId);
  }
  githubToken(userId) {
    const saved = this.data.integrations[userId]?.github;
    if (!saved) throw new DomainError(404, "Connect your personal GitHub account first");
    return this.decrypt(userId, "integration:github", saved.secret);
  }
  async githubRepos(userId) {
    const repos = await this.githubFetch(this.githubToken(userId),
      "/user/repos?per_page=40&sort=updated&affiliation=owner,collaborator");
    if (!Array.isArray(repos)) throw new DomainError(502, "GitHub returned no repository list");
    return repos.slice(0, 40).map(r => ({ fullName: String(r.full_name || "").slice(0, 160),
      description: String(r.description || "").slice(0, 300), private: !!r.private,
      defaultBranch: String(r.default_branch || ""), updatedAt: r.updated_at ?? null }));
  }
  async githubReadme(userId, repository) {
    if (typeof repository !== "string" ||
      !/^[A-Za-z0-9_.-]{1,100}\/[A-Za-z0-9_.-]{1,100}$/.test(repository)) {
      throw new DomainError(400, "Invalid GitHub repository name");
    }
    const file = await this.githubFetch(this.githubToken(userId),
      "/repos/" + repository + "/readme");
    if (file.encoding !== "base64" || typeof file.content !== "string" ||
        file.content.length > 180000 || file.size > 100000) {
      throw new DomainError(413, "GitHub README must be a text document under 100 KB");
    }
    const decoded = Buffer.from(file.content.replace(/\s/g, ""), "base64");
    if (decoded.length > 100000 || decoded.includes(0)) {
      throw new DomainError(400, "Unsupported GitHub README content");
    }
    return decoded.toString("utf8").slice(0, 45000);
  }

  attachments(userId) {
    return Object.values(this.data.attachments[userId] ?? {}).map(({ id, name, mimeType, size, createdAt }) =>
      ({ id, name, mimeType, size, createdAt })).sort((a, b) => b.createdAt - a.createdAt);
  }
  saveAttachment(userId, { name, mimeType, base64 }) {
    const bytes = validateFile({ name, mimeType, base64 });
    if (!this.vaultReady) throw new DomainError(503, "Secure vault unavailable on this backend");
    const mine = this.data.attachments[userId] ??= {};
    const files = Object.values(mine);
    if (files.length >= 12 || files.reduce((sum, f) => sum + f.size, bytes.length) > 10 * MAX_ATTACHMENT_BYTES) {
      throw new DomainError(409, "Attachment limit reached. Remove older files first.");
    }
    const id = randomUUID();
    const record = { id, name, mimeType, size: bytes.length, createdAt: this.now(),
      secret: this.encrypt(userId, "file:" + id, bytes.toString("base64")) };
    mine[id] = record;
    this.commit("account.attachment.saved", { userId, attachmentId: id });
    const { secret, ...metadata } = record;
    return metadata;
  }
  deleteAttachment(userId, id) {
    const mine = this.data.attachments[userId];
    if (!mine?.[id]) throw new DomainError(404, "Attachment unavailable");
    delete mine[id];
    this.commit("account.attachment.deleted", { userId, attachmentId: id });
    return { removed: true };
  }
  resolveAttachments(userId, ids) {
    if (!Array.isArray(ids) || ids.length > 3 || new Set(ids).size !== ids.length) {
      throw new DomainError(400, "Choose up to three different attachments");
    }
    return ids.map(id => {
      const file = this.data.attachments[userId]?.[id];
      if (!file) throw new DomainError(404, "Attachment unavailable");
      const binary = this.decrypt(userId, "file:" + id, file.secret);
      return attachmentForModel(file, binary);
    });
  }

  threads(userId) {
    return Object.values(this.data.threads[userId] ?? {}).map(t => ({
      id: t.id, agentId: t.agentId, provider: t.provider, title: t.title,
      updatedAt: t.updatedAt, messageCount: t.messages.length,
    })).sort((a,b) => b.updatedAt - a.updatedAt).slice(0, 100);
  }
  thread(userId, threadId) {
    const thread = this.data.threads[userId]?.[threadId];
    if (!thread) throw new DomainError(404, "Conversation unavailable");
    return thread;
  }
}
